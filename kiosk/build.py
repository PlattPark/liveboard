#!/usr/bin/env python3
"""Builds kiosk/launcher.html - the page the TV box opens first.

Why it exists: the wall is a web page, so when Edge starts with no connection (the nightly restart racing the
Wi-Fi, a power blip, a real outage) it shows its own "not connected to the internet" page and stays there until
someone restarts the box (Nov 15 2026: an hour of that on a Sunday open). This file is saved ON the box, so it
always loads. It checks that the board can really be fetched, then opens it; until then it shows a plain holding
card and keeps checking. Nothing here needs the network to render: fonts and logo are embedded.

    python3 kiosk/build.py            # rewrites kiosk/launcher.html from fonts/ and src/img/logo.png

The box setup is in kiosk/README.md. The built file is committed so the box can download it straight from the site.
"""
import base64, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BOARD = "https://plattpark.github.io/liveboard/platt-park-live-board-v4.html"

def b64(p):
    return base64.b64encode((ROOT / p).read_bytes()).decode()

PAGE = r"""<!DOCTYPE html>
<!-- GENERATED by kiosk/build.py - edit that, not this. Saved on the TV box; opens the tap board once it can be reached. -->
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width">
<title>Platt Park Brewing Co. — Tap Board</title>
<style>
@font-face{font-family:'Archivo Black';src:url(data:font/woff2;base64,@@ARCHIVO@@) format('woff2');ascent-override:87.8%;descent-override:21%;line-gap-override:0%}
@font-face{font-family:'Barlow';font-weight:700;src:url(data:font/woff2;base64,@@BARLOW@@) format('woff2')}
html,body{height:100%;margin:0}
body{background:#293d22;color:#e7eacd;overflow:hidden;cursor:none;font-family:'Barlow','Segoe UI',Arial,sans-serif}
#card{position:fixed;top:0;left:0;right:0;bottom:0;display:flex;flex-direction:column;align-items:center;justify-content:center;gap:3.2vh;text-align:center;opacity:0;transition:opacity .8s}
#card.on{opacity:1}
#card img{height:30vh;width:auto}
.line{font-family:'Archivo Black','Arial Black','Segoe UI',sans-serif;font-size:4.6vh;letter-spacing:.2vh;text-transform:uppercase;color:#e7eacd;text-shadow:.3vh .3vh 0 rgba(255,90,58,.4)}
.sub{font-weight:700;font-size:2.3vh;letter-spacing:.22vh;text-transform:uppercase;color:#eebf19}
#st{position:fixed;left:0;right:0;bottom:2.4vh;text-align:center;font-weight:700;font-size:1.5vh;letter-spacing:.12vh;text-transform:uppercase;color:#8fa27a;opacity:0;transition:opacity .8s}
#card.on ~ #st{opacity:1}
</style>
</head>
<body>
<div id="card">
  <img alt="Platt Park Brewing Co." src="data:image/png;base64,@@LOGO@@">
  <div class="line">The tap list will be right back</div>
  <div class="sub">Ask your bartender what's pouring</div>
</div>
<div id="st"></div>
<script>
(function(){
  var BOARD = '@@BOARD@@';
  var card = document.getElementById('card'), st = document.getElementById('st');
  var tries = 0, good = 0, blind = 0, gone = false;

  function clock(){ var d = new Date(), h = d.getHours(), m = d.getMinutes(); return ((h % 12) || 12) + ':' + (m < 10 ? '0' : '') + m + (h < 12 ? ' am' : ' pm'); }

  // fetch with a deadline, so a connection that hangs counts as a miss instead of stalling the loop
  function get(opts){
    var ctl = ('AbortController' in window) ? new AbortController() : null;
    if(ctl) opts.signal = ctl.signal;
    var timer = setTimeout(function(){ if(ctl) ctl.abort(); }, 8000);
    var url = BOARD + (BOARD.indexOf('?') < 0 ? '?' : '&') + 'launch=' + Date.now();
    return fetch(url, opts).then(function(r){ clearTimeout(timer); return r; }, function(e){ clearTimeout(timer); throw e; });
  }

  // 'ok' = the board was fetched and read; 'blind' = it could not be read but a blind request got through (the
  // connection is fine, only the read was refused); 'site' = online but the board isn't being served; 'offline' = nothing.
  function look(){
    return get({cache:'no-store'}).then(function(r){
      if(!r.ok) return 'site';
      return r.text().then(function(t){ return (t.length > 20000 && t.indexOf('</html>') > 0) ? 'ok' : 'site'; }, function(){ return 'offline'; });
    }, function(){
      return get({mode:'no-cors', cache:'no-store'}).then(function(){ return 'blind'; }, function(){ return 'offline'; });
    });
  }

  function open(){ gone = true; location.replace(BOARD); }

  function check(){
    tries++;
    look().then(function(res){
      // two of the same good answer in a row before opening: a Wi-Fi link that is still settling doesn't count
      if(res === 'ok'){ good++; blind = 0; } else if(res === 'blind'){ blind++; good = 0; } else { good = 0; blind = 0; }
      if(good >= 2 || blind >= 2){ open(); return; }
      if(res === 'ok' || res === 'blind'){ setTimeout(check, 1500); return; }
      st.textContent = (res === 'site' ? 'Online, but the tap list site is not answering' : 'No internet connection at the TV box')
                     + ' \u00b7 checking again every few seconds \u00b7 last check ' + clock();
      setTimeout(check, tries < 12 ? 5000 : 10000);
    });
  }
  // a normal start has the board up in a couple of seconds and never shows the card - only a real wait does
  setTimeout(function(){ if(gone) return; card.className = 'on'; if(!st.textContent) st.textContent = 'Connecting to the tap list'; }, 6000);
  check();
})();
</script>
</body>
</html>
"""

def main():
    out = (PAGE.replace("@@ARCHIVO@@", b64("fonts/archivoblack.woff2"))
               .replace("@@BARLOW@@", b64("fonts/barlow-700.woff2"))
               .replace("@@LOGO@@", b64("src/img/logo.png"))
               .replace("@@BOARD@@", BOARD))
    assert "@@" not in out
    dest = Path(__file__).resolve().parent / "launcher.html"
    dest.write_text(out, encoding="utf-8")
    print("wrote %s (%d KB)" % (dest.relative_to(ROOT), len(out) // 1024))

if __name__ == "__main__":
    main()
